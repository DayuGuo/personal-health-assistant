export interface InstallOptions {
  root: string;
  state: SetupState;
  run: Runner;
  loadClients: () => Promise<Clients>;
  confirmDeploy: () => Promise<void>;
  progress: (message: string) => void;
  authorize?: typeof authorizeHealth;
  fetcher?: typeof fetch;
  reauthorize?: boolean;
  hostnameCheck?: (state: SetupState) => Promise<void>;
}
export async function install(options: InstallOptions): Promise<Probe[] | null> {
  const { root, state, run, progress } = options;
  validateState(state);
  await assertManaged(root, state);
  if (!state.accountId) throw Error('Select a Cloudflare account first');
  await saveState(root, state);
  if (!state.deploymentAttempted) {
    await (options.hostnameCheck ?? assertUnusedHostname)(state);
    const result = await run(['deployments', 'list', '--name', state.workerName]);
    if (result.code === 0)
      throw Error(
        'A Worker with this name already exists. It was preserved. Choose a different name in a clean clone.',
      );
    if (!isMissingWorker(result.stdout + result.stderr))
      throw Error(
        'Could not safely establish that the Worker name is unused. Check Cloudflare account access; no deployment was attempted.',
      );
  }
  for (const kind of ['auth', 'cache'] as const) {
    const key = kind === 'auth' ? 'authId' : 'cacheId';
    if (state[key]) continue;
    const title = `${state.workerName}-${kind}-${state.installId}`;
    const list = await requireCommand(run, ['kv', 'namespace', 'list']);
    const namespaces = JSON.parse(list.stdout) as { title: string; id: string }[];
    const found = namespaces.filter((n) => n.title === title);
    if (found.length > 1) throw Error('Ambiguous namespace title; no resources were overwritten');
    if (found[0]) state[key] = found[0].id;
    else {
      progress(`Create KV / 创建 KV: ${kind}`);
      const result = await requireCommand(run, [
        'kv',
        'namespace',
        'create',
        title,
        '--update-config=false',
      ]);
      state[key] = namespaceId(result.stdout);
    }
    validateState(state);
    await saveState(root, state);
  }
  await renderSite(root, state);
  if (!state.publicDeployed) {
    await options.confirmDeploy();
    state.deploymentAttempted = true;
    await saveState(root, state);
    progress('Deploy public pages and MCP / 部署公开页面与 MCP');
    await requireCommand(run, ['deploy']);
    state.publicDeployed = true;
    await saveState(root, state);
  }
  progress('Verify HTTPS and OAuth discovery / 验证 HTTPS 与 OAuth 发现');
  await verifyPublic(state.origin, options.fetcher);
  let probes: Probe[] | null = null;
  if (!state.healthAuthorized || options.reauthorize) {
    const clients = await options.loadClients();
    progress('Upload client credentials / 上传客户端凭据');
    await requireCommand(run, ['secret', 'bulk'], JSON.stringify(clients));
    probes = await (options.authorize ?? authorizeHealth)({
      clients,
      ownerEmail: state.ownerEmail,
      run,
      announce: progress,
    });
    state.healthAuthorized = true;
    state.healthVerifiedAt = probes.every((p) => p.ok) ? new Date().toISOString() : undefined;
    await saveState(root, state);
    probes.forEach((p) => progress(JSON.stringify(p)));
  }
  if (state.healthAuthorized && !state.healthVerifiedAt)
    throw Error(
      'Authorization was saved, but Health verification is incomplete. Rerun with --reauthorize after resolving API access.',
    );
  if (state.daily === 'guide') await exportDailyGuide(root);
  await writeFile(resolve(root, '.setup/CONNECT.md'), connectionGuide(state));
  if (probes?.some((p) => !p.ok))
    throw Error(
      'Authorization was saved, but some Health reads failed. Resolve API access, then use --reauthorize or diagnose:health.',
    );
  return probes;
}
