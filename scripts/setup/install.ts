const hash = (text: string) => createHash('sha256').update(text).digest('hex');
export async function exists(path: string): Promise<boolean> {
  try {
    await readFile(path);
    return true;
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return false;
    throw e;
  }
}
export async function loadState(root: string): Promise<SetupState | null> {
  const file = resolve(root, '.setup/state.json'),
    next = resolve(root, '.setup/state.next.json');
  const old = (await exists(file))
    ? validateState(JSON.parse(await readFile(file, 'utf8')) as SetupState)
    : null;
  // Complete an interrupted atomic checkpoint only if the config matches it and
  // it belongs to the same installation. Never adopt arbitrary legacy config.
  if (await exists(next)) {
    const candidate = validateState(JSON.parse(await readFile(next, 'utf8')) as SetupState);
    if (
      (!old || candidate.installId === old.installId) &&
      (await exists(resolve(root, 'wrangler.toml'))) &&
      hash(await readFile(resolve(root, 'wrangler.toml'), 'utf8')) === candidate.configHash
    ) {
      await rename(next, file);
      return candidate;
    }
  }
  return old;
}
export async function assertManaged(root: string, state: SetupState): Promise<void> {
  const config = resolve(root, 'wrangler.toml');
  if (await exists(config)) {
    const current = await readFile(config, 'utf8');
    if (!state.configHash || hash(current) !== state.configHash)
      throw Error(
        'Existing wrangler.toml was not generated by this installer or was edited. It was preserved. Use a clean clone for a new installation.',
      );
  } else if (state.configHash)
    throw Error(
      'The generated configuration is missing. Restore it or use a clean clone; no cloud resources were changed.',
    );
}
export async function saveState(root: string, state: SetupState): Promise<void> {
  await assertManaged(root, state);
  await mkdir(resolve(root, '.setup'), { recursive: true, mode: 0o700 });
  const config = renderConfig(state);
  state.configHash = hash(config);
  // Write-ahead state lets an interrupted config replacement be recovered explicitly.
  await writeFile(resolve(root, '.setup/wrangler.next.toml'), config, { mode: 0o600 });
  await writeFile(resolve(root, '.setup/state.next.json'), JSON.stringify(state, null, 2) + '\n', {
    mode: 0o600,
  });
  await rename(resolve(root, '.setup/wrangler.next.toml'), resolve(root, 'wrangler.toml'));
  await rename(resolve(root, '.setup/state.next.json'), resolve(root, '.setup/state.json'));
}
export async function verifyPublic(origin: string, fetcher: typeof fetch = fetch): Promise<void> {
  const get = (path: string) =>
    fetcher(origin + path, { redirect: 'error', signal: AbortSignal.timeout(20000) });
  for (const path of ['/', '/privacy/', '/terms/', '/health']) {
    const response = await get(path);
    if (response.status !== 200)
      throw Error(
        `Public verification failed (${path}, HTTP ${response.status}). Check DNS/TLS and resume.`,
      );
    if (path === '/health') {
      const body = (await response.json()) as { mode?: string };
      if (body.mode !== 'read-only')
        throw Error('The hostname does not serve the expected read-only Worker.');
    } else await response.body?.cancel();
  }
  const challenge = await get('/mcp');
  const metadata = challenge.headers
    .get('www-authenticate')
    ?.match(/resource_metadata="([^"]+)"/)?.[1];
  if (challenge.status !== 401 || !metadata || new URL(metadata).origin !== origin)
    throw Error('Protected MCP discovery failed');
  const resourceResponse = await fetcher(metadata, {
    redirect: 'error',
    signal: AbortSignal.timeout(20000),
  });
  const resource = (await resourceResponse.json()) as {
    resource?: string;
    authorization_servers?: string[];
  };
  if (
    !resourceResponse.ok ||
    resource.resource !== origin + '/mcp' ||
    !resource.authorization_servers?.includes(origin)
  )
    throw Error('OAuth resource metadata points to another deployment');
  const response = await get('/.well-known/oauth-authorization-server');
  const server = (await response.json()) as {
    authorization_endpoint?: string;
    token_endpoint?: string;
    client_id_metadata_document_supported?: boolean;
  };
  if (
    !response.ok ||
    server.authorization_endpoint !== origin + '/authorize' ||
    server.token_endpoint !== origin + '/oauth/token' ||
    server.client_id_metadata_document_supported !== true
  )
    throw Error('OAuth/CIMD discovery failed');
}
export async function assertUnusedHostname(
  state: SetupState,
  resolver: (hostname: string) => Promise<unknown> = (hostname) => lookup(hostname, { all: true }),
): Promise<void> {
  if (!state.domainBinding) return;
  let used = false;
  try {
    await resolver(new URL(state.origin).hostname);
    used = true;
  } catch (e) {
    if (!['ENOTFOUND', 'ENODATA'].includes((e as NodeJS.ErrnoException).code ?? ''))
      throw Error('Could not safely check hostname DNS. No domain binding was attempted.');
  }
  if (used)
    throw Error(
      'The custom hostname already resolves in DNS and was preserved. Choose an unused hostname or workers.dev; the installer will not replace an existing DNS record.',
    );
}
